export function pt(lang, key) {
  const l = normalizeLang(lang);
  const table = PANEL_DICT[l] || PANEL_DICT.pt;
  return Object.prototype.hasOwnProperty.call(table, key) ? table[key] : (PANEL_DICT.pt[key] || key);
}

export function applyPanelI18n(lang) {
  if (typeof document === 'undefined') return;
  const l = normalizeLang(lang);
  document.documentElement.lang = l === 'en' ? 'en' : (l === 'es' ? 'es' : 'pt-BR');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = pt(l, el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = pt(l, el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', pt(l, el.getAttribute('data-i18n-placeholder')));
  });
}
